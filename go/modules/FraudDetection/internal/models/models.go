package frauddetection

import "time"

// FraudEvent represents a fraud detection event
type FraudEvent struct {
	ID          string  `json:"id"`
	UserID      string  `json:"user_id"`
	EventType   string  `json:"event_type"`   // login, transaction, payment
	RiskScore   float64 `json:"risk_score"`   // 0-100
	Status      string  `json:"status"`       // flagged, confirmed, resolved
	Details     string  `json:"details"`
	IPAddress   string  `json:"ip_address"`
	UserAgent   string  `json:"user_agent"`
	CreatedAt   string  `json:"created_at"`
	ResolvedAt  string  `json:"resolved_at"`
}

// FraudAlert represents a fraud alert generated by the system
type FraudAlert struct {
	ID            int64     `json:"id"`
	UserID        string    `json:"user_id"`
	TransactionID string    `json:"transaction_id"`
	Type          string    `json:"type"` // e.g., transaction, login
	RiskLevel     string    `json:"risk_level"` // low, medium, high, critical
	Score         float64   `json:"score"`
	Details       string    `json:"details"`
	Status        string    `json:"status"` // open, resolved, false_positive
	CreatedAt     time.Time `json:"created_at"`
	ResolvedAt    *time.Time `json:"resolved_at,omitempty"`
}

// FraudRule defines a rule for fraud detection
type FraudRule struct {
	ID          int64     `json:"id"`
	Name        string    `json:"name"`
	Description string    `json:"description"`
	RuleType    string    `json:"rule_type"` // amount, frequency, location, etc.
	Type        string    `json:"type"`      // repository column
	Condition   string    `json:"condition"` // JSON encoded condition
	Action      string    `json:"action"`    // block, alert, etc.
	RiskScore   float64   `json:"risk_score"`
	Severity    float64   `json:"severity"` // for repository
	IsActive    bool      `json:"is_active"`
	IsEnabled   bool      `json:"is_enabled"` // for repository
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
}

// FraudCase represents a manual fraud investigation case
type FraudCase struct {
	ID          int64     `json:"id"`
	AlertID     int64     `json:"alert_id"`
	UserID      string    `json:"user_id"`
	Status      string    `json:"status"` // open, investigating, closed
	Description string    `json:"description"`
	Resolution  string    `json:"resolution"`
	CreatedAt   time.Time `json:"created_at"`
	UpdatedAt   time.Time `json:"updated_at"`
}
