export function getModuleNames(): string[] {
  return Object.keys(modules);
}

export function getRequiredModules(): string[] {
  return Object.entries(moduleMetadata)
    .filter(([_, meta]) => meta.required)
    .map(([name]) => name);
}

export function getModulesByCategory(category: string): string[] {
  return Object.entries(moduleMetadata)
    .filter(([_, meta]) => meta.category === category)
    .map(([name]) => name);
}

export function getModulePriority(name: string): number {
  return moduleMetadata[name as keyof typeof moduleMetadata]?.priority ?? 99;
}
