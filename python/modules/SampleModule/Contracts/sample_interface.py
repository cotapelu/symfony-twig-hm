# Sample Interface defining contracts between layers
from typing import Protocol, Optional

class SampleRepositoryInterface(Protocol):
    def save(self, entity: 'SampleEntity') -> None: ...
    def find_by_id(self, entity_id: int) -> Optional['SampleEntity']: ...
    def find_all(self) -> list['SampleEntity']: ...
    def delete_by_id(self, entity_id: int) -> None: ...